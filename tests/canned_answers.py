"""인수 시험이 짜 둔 **모델 답** — 예제가 그 값이어야 뜻이 통하는 자리 (`tests/stub_model.py`).

**이것은 제품 코드가 아니다.** 답은 모델이 아니라 **시험이 정한다** — 시험하는 것은 모델의
똑똑함이 아니라 **엔진·케이스·기대값이 한 줄로 맞물리는가**다.

**자리가 하나다.** M3(재무·기능)·M5(업무 앱)·M7(서버 재통과) 묶음이 같은 예제를 돌리므로, 답이
묶음마다 따로 있으면 **같은 그림이 묶음에 따라 다른 답을 받는다** — M7이 세 예제를 돌리지 못한
까닭이 그것이었다 (`_NO_CANNED`). 그래서 이 파일로 모았다.

열쇠는 `results`의 **이름들**(정렬한 튜플)이다. `given`은 C14 §「AI 태스크가 보는 값」대로
모델에게 간 값이라 건마다 다른 답(반복)도 여기서 만든다. **열쇠가 겹치지 않는다** — 겹치면
한 예제의 답이 다른 예제를 조용히 바꾼다 (`test_no_two_examples_share_a_key`가 막는다).
"""

from __future__ import annotations

import re
from typing import Any


def _invoice(발주번호: str, 공급가액: int, *, 부가세: int | None = None) -> dict[str, Any]:
    세액 = round(공급가액 * 0.1) if 부가세 is None else 부가세
    return {
        "공급사": "한빛상사",
        "청구번호": f"IV-{발주번호}",
        "발주번호": 발주번호,
        "공급가액": 공급가액,
        "부가세": 세액,
        "합계": 공급가액 + 세액,
    }

LEDGER = [
    {"발주번호": "PO-1", "공급사": "한빛상사", "공급가액": 2780000, "입고": True},
    {"발주번호": "PO-2", "공급사": "가온테크", "공급가액": 3000000, "입고": True},
    {"발주번호": "PO-4", "공급사": "다래물산", "공급가액": 1000000, "입고": True},
    {"발주번호": "PO-5", "공급사": "마바상사", "공급가액": 1500000, "입고": False},
    {"발주번호": "PO-6", "공급사": "사아공업", "공급가액": 2000000, "입고": True},
    {"발주번호": "PO-8", "공급사": "자차산업", "공급가액": 900000, "입고": True},
    {"발주번호": "PO-9", "공급사": "카타테크", "공급가액": 800000, "입고": True},
]

INVOICES = [
    _invoice("PO-1", 2780000),
    _invoice("PO-2", 3000000),
    _invoice("PO-없음", 500000),
    _invoice("PO-4", 1000001),
    _invoice("PO-5", 1500000),
    _invoice("PO-6", 2000000),
    _invoice("PO-6", 2000000),
]

CLEAN_INVOICES = [_invoice("PO-1", 2780000), _invoice("PO-2", 3000000)]

def _number(path: str) -> int:
    """`invoice_2026-08_3.pdf` → 3 (없으면 1). 반복에서 건을 가르는 데 쓴다."""
    found = re.findall(r"_(\d+)\.pdf$", path)
    return int(found[0]) if found else 1


def canned(wanted: dict[str, str], given: dict[str, Any]) -> dict[str, Any] | None:
    """`(받을 필드, 함께 온 값)` → 짜 둔 답 (없으면 `None` — 스텁이 타입으로 때운다)."""
    key = tuple(sorted(wanted))

    # ── 재무·기능 예제 (BX-01·02·05·07·30·37, FX-01·06·08·09) ──
    if key == ("발주목록",):  # BX-01 발주 대장
        return {"발주목록": LEDGER}
    if key == ("청구",):  # BX-01 청구서 한 장 (반복) — 파일 이름의 번호로 건을 가른다
        number = _number(str(given.get("청구서", "")))
        clean = "2026-07" in str(given.get("청구서", ""))
        table = CLEAN_INVOICES if clean else INVOICES
        return {"청구": table[(number - 1) % len(table)]}
    if key == ("기준일", "환율"):  # BX-02
        return {"환율": {"KRW": 1387.5, "EUR": 0.92, "JPY": 151.3}, "기준일": "2026-09-30"}
    if key == ("원화",):  # FX-01·FX-08
        if "invalid" in str(given.get("주소", "")):
            # FX-08은 **실패해야** 오류 경계가 받는다. 스텁은 도구를 부르지 않으므로 「수를
            # 못 냈다」로 답한다 — `results` 검증이 업무 실패로 올리고, 거기서 대체 경로다.
            return {"원화": "모름"}
        return {"원화": 1350}
    if key == ("분개초안", "불일치"):  # BX-05
        return {"분개초안": [{"계정": "미지급금", "금액": 1000}], "불일치": []}
    if key == ("내역",):  # BX-07 카드 내역
        return {"내역": [
            {"승인번호": "A1", "일시": "2026-09-21 12:10", "요일": "월", "시": 12,
             "가맹점": "한빛식당", "업종": "음식점", "금액": 18000, "사용자": "김책사"},
            {"승인번호": "A2", "일시": "2026-09-26 23:40", "요일": "토", "시": 23,
             "가맹점": "밤길택시", "업종": "택시", "금액": 32000, "사용자": "이책사"},
        ] if "W4" in str(given.get("내역파일", "")) else [
            {"승인번호": "B1", "일시": "2026-09-15 12:10", "요일": "화", "시": 12,
             "가맹점": "한빛식당", "업종": "음식점", "금액": 18000, "사용자": "김책사"},
        ]}
    if key == ("분류",):  # BX-07 계정과목 (반복)
        건 = given.get("건") or {}
        업종 = str(건.get("업종", ""))
        계정 = {"음식점": "복리후생비", "택시": "여비교통비"}.get(업종, "소모품비")
        return {"분류": {"승인번호": 건.get("승인번호", ""), "계정과목": 계정, "근거": f"{업종} 기본 계정"}}
    if key == ("손해배상조항", "지재권조항", "해지조항"):  # BX-30
        높음 = "unlimited" in str(given.get("계약서", ""))
        return {
            "손해배상조항": "모든 손해를 배상한다" if 높음 else "직접 손해로 한정한다",
            "지재권조항": "산출물의 권리는 갑에게 있다",
            "해지조항": "30일 전 서면 통지로 해지할 수 있다",
        }
    if key == ("의견서",):  # BX-30
        return {"의견서": "손해배상 범위를 직접 손해로 한정할 것을 권합니다."}
    if key == ("결과",):  # BX-37 조항 검토 (BX-30이 호출하기도 한다)
        조항 = str(given.get("조항", ""))
        # 빈 조항은 「판단할 거리가 없다」 3, 무제한 배상은 5, 표준 문구는 1.
        점수 = 3 if not 조항.strip() else (5 if "모든 손해" in 조항 else 1)
        return {"결과": {"점수": 점수, "사유": "표준 범위" if 점수 < 4 else "배상 범위가 무제한이다"}}
    if key == ("견적",):  # FX-06
        return {"견적": {"공급사": "한빛상사", "합계": 1320000}}
    if key == ("판정",):  # FX-09 신청 한 건 (반복)
        신청 = given.get("신청") or {}
        승인 = bool(신청.get("영수증")) and int(신청.get("금액", 0)) <= 50000
        return {"판정": {"id": 신청.get("id"), "승인": 승인, "사유": "기준 충족" if 승인 else "기준 미달"}}

    # ── 업무 앱 예제 (BX-08·10·13·15·20·23·31·32·34·35, FX-10) ──
    if key == ("메일",):
        # BX-08과 BX-23이 **같은 모양**을 돌려준다 — `대상`의 칸으로 가른다.
        대상 = given.get("대상") or {}
        if "교육명" in 대상:  # BX-23 교육 독려
            단계 = str(대상.get("단계", ""))
            참조 = [대상.get("팀장메일")] if 단계 in ("팀장참조", "인사팀보고") else []
            if 단계 == "인사팀보고":
                참조 = [*참조, given.get("인사팀메일")]
            return {
                "메일": {
                    "받는사람": 대상.get("메일"),
                    "참조": [one for one in 참조 if one],
                    "제목": f"[{단계}] {대상.get('교육명')} 이수 안내",
                    "본문": f"{대상.get('이름')}님, {대상.get('마감일')}까지 {대상.get('링크')}에서 이수해 주세요.",
                }
            }
        # BX-08 연체 독촉
        return {
            "메일": {
                "받는사람": f"{대상.get('거래처명')} 담당자",
                "제목": f"[{대상.get('단계')}] 미결제 안내",
                "본문": f"{대상.get('거래처명')} 귀중, {대상.get('금액')}원이 {대상.get('연체일수')}일 지났습니다.",
            }
        }

    if key == ("서류결과",):  # BX-10 서류 확인
        서류 = [str(one) for one in (given.get("서류") or [])]
        통장 = any("bank" in one for one in 서류)
        사업자 = any("biz" in one for one in 서류)
        빠진 = [name for name, 있다 in (("사업자등록증", 사업자), ("통장 사본", 통장)) if not 있다]
        return {"서류결과": {"충족": not 빠진, "빠진서류": 빠진, "불일치": []}}

    if key == ("근거", "분류"):  # BX-13 반품 사유 분류
        사유 = str(given.get("사유", ""))
        if "안 켜" in 사유 or "고장" in 사유 or "불량" in 사유:
            return {"분류": "불량", "근거": "제품이 동작하지 않는다고 적혀 있다"}
        if "다른" in 사유 or "오배송" in 사유:
            return {"분류": "오배송", "근거": "주문과 다른 물건이 왔다고 적혀 있다"}
        return {"분류": "단순변심", "근거": "제품 하자를 말하지 않는다"}

    if key == ("문단",):  # BX-15 견적서 문단
        고객 = given.get("고객") or {}
        return {"문단": f"{고객.get('이름', '고객')}님께 아래와 같이 견적을 보내 드립니다."}

    if key == ("환영본문",):  # BX-20 환영 메일
        return {
            "환영본문": (
                f"{given.get('이름')}님, {given.get('부서')} 합류를 환영합니다. "
                f"{given.get('입사일')} 첫 출근이며 회사 메일은 {given.get('회사메일')}입니다. "
                f"{given.get('첫날안내')}"
            )
        }

    if key == ("긴급도", "요약", "종류", "확신도"):  # BX-31 요청 분류
        본문 = str(given.get("본문", ""))
        if "노트북" in 본문 or "화면" in 본문:
            # 확신도 0.8 이상이면 사람 확인을 건너뛴다 (「노트북 고장」 케이스).
            return {"종류": "장비", "긴급도": "높음", "요약": "노트북 화면 불량", "확신도": 0.92}
        # 애매한 요청 — 확신도가 낮아 사람에게 간다.
        return {"종류": "기타", "긴급도": "보통", "요약": "내용이 불분명한 요청", "확신도": 0.21}

    if key == ("근거부족", "초안"):  # BX-32 답변 초안
        근거 = given.get("근거") or []
        if not 근거:
            return {"초안": "", "근거부족": True}
        첫 = 근거[0] if isinstance(근거[0], dict) else {}
        return {
            "초안": f"안녕하세요 고객님. {첫.get('본문', '')}",
            "근거부족": False,
        }

    if key == ("분석",):  # BX-35 묶음 하나 분석 (반복)
        한묶음 = given.get("한묶음") or []
        found = []
        for one in 한묶음:
            제목 = str(one.get("subject", "")) if isinstance(one, dict) else ""
            주제 = 제목[제목.find("[") + 1 : 제목.find("]")] if "[" in 제목 and "]" in 제목 else ""
            주제 = 주제 or "기타"
            감성 = "부정" if 주제 in ("배송", "환불", "품질") else "긍정"
            found.append({"주제": 주제, "감성": 감성})
        return {"분석": found}

    if key == ("요약",):  # BX-35 한 장 요약
        주제별 = given.get("주제별") or {}
        return {"요약": f"주제 {len(주제별)}가지를 보았고 부정 비율은 {given.get('부정비율')}입니다."}

    if key == ("요약", "원인후보"):  # BX-34 장애 요약
        로그 = given.get("로그") or []
        return {
            "요약": f"{given.get('서비스')}에서 오류가 늘고 있습니다. 로그 {len(로그)}줄을 확인했습니다.",
            "원인후보": ["상위 결제 게이트웨이 지연 (추정)", "회로 차단기 반개방 (추정)"],
        }

    if key == ("intent",):  # FX-10 라우팅
        요청 = str(given.get("요청", ""))
        if "환율" in 요청 or "달러" in 요청:
            return {"intent": "exchange_rate"}
        if 요청.startswith("http"):
            return {"intent": "web_summary"}
        return {"intent": "answer"}

    if key == ("답",):
        # 환율 태스크는 `주소`를 받는다 (`domain: api`). 스텁은 도구를 부르지 않는다.
        if "주소" in given:
            return {"답": "오늘 USD/KRW는 1,387.5원입니다."}
        return {"답": f"「{given.get('요청')}」은 사내 안내 페이지를 확인해 주세요."}

    # ── FX-23 재생 모드 셋 (plan·full·none) ──
    #
    # **세 태스크가 같은 답을 내야** 「다른 것은 모델을 몇 번 부르나뿐」이라는 말이 선다.
    # 열쇠는 `results` 이름이라 BX-07의 `("분류",)`와 겹치지 않게 `문의갈래`로 두었다 —
    # 겹치면 한 예제의 답이 다른 예제를 조용히 바꾼다 (`test_no_two_examples_share_a_key`).
    if key == ("문의갈래",):
        문의 = str(given.get("문의", ""))
        return {"문의갈래": "파손" if "깨" in 문의 or "파손" in 문의 else "문의"}
    if key == ("기록결과",):
        return {"기록결과": "장부에 한 줄 더했습니다"}
    if key == ("말투",):
        return {"말투": "정중"}

    return None


